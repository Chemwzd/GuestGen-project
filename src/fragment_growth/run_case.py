#!/usr/bin/env python3
"""Prepare (and optionally run) one fragment-growth case.

The script writes a self-contained run directory that contains everything the
growth engine needs:

* ``ligED.npy`` - the ligand electron-density grid (N x 4 columns ``x y z rho``,
  Fortran-ordered, masked), built from a guest ED ``.npy`` generated by the
  ED-VAE inference step;
* ``<target>.sdf`` - the receptor structure converted from the host MOL;
* ``config.ini`` - the engine configuration;
* ``run_manifest.json`` - parameters recorded for the run.

With ``--execute`` the growth engine runs immediately; without it the case is
only prepared, so inputs can be inspected first.
"""

from __future__ import annotations

import argparse
import configparser
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np
from rdkit import Chem


# Cases whose host contains a metal center; their host-guest complex
# optimization uses the ALPB water solvation model in binding mode.
METAL_CASES = {
    "cekdec",
    "tupboz",
    "gehroe",
    "qodnik",
    "sohxof",
    "femsew",
    "giymux",
    "humjil",
    "xezbaf",
    "qupyik",
}


def rho_to_liged_grid(rho: np.ndarray, step_size: float, mask: float | None) -> np.ndarray:
    """Convert a 48^3 density array into the engine's N x 4 grid.

    The coordinates follow the convention of the released runs: the box size is
    ``(48 - 1) * step_size``, the effective spacing is ``box_size / 48`` (not
    ``step_size``), the origin is ``-box_size / 2``, and the columns are
    flattened in Fortran order.
    """

    if rho.shape != (48, 48, 48):
        raise ValueError(f"Expected 48^3 generated ED, got {rho.shape}")
    values = np.array(rho, dtype=np.float32, copy=True)
    if mask is not None:
        values[values <= mask] = 0.0
    nx, ny, nz = values.shape
    box_size = (nx - 1) * step_size
    spacing = box_size / nx
    origin = -0.5 * box_size
    x = origin + np.arange(nx) * spacing
    y = origin + np.arange(ny) * spacing
    z = origin + np.arange(nz) * spacing
    xx, yy, zz = np.meshgrid(x, y, z, indexing="ij")
    return np.column_stack(
        [
            xx.flatten(order="F"),
            yy.flatten(order="F"),
            zz.flatten(order="F"),
            values.flatten(order="F"),
        ]
    )


def resolve_executable(value: str | None) -> str | None:
    if not value:
        return None
    resolved = shutil.which(value)
    if resolved:
        return resolved
    path = Path(value).expanduser().resolve()
    return str(path) if path.is_file() and os.access(path, os.X_OK) else None


def convert_mol_to_sdf(
    source: Path,
    destination: Path,
    obabel: str | None,
    allow_rdkit_fallback: bool = False,
) -> str:
    """Convert the host MOL to a receptor SDF.

    Open Babel is the default converter. The RDKit fallback exists for
    environments without Open Babel and must be requested explicitly.
    """

    if obabel:
        executable = resolve_executable(obabel)
        if executable:
            subprocess.run(
                [str(executable), str(source), "-O", str(destination)], check=True
            )
            return str(executable)
    if not allow_rdkit_fallback:
        raise FileNotFoundError(
            "Open Babel is unavailable. Set OBABEL_BIN / --obabel, or pass "
            "--allow-rdkit-converter to use the RDKit converter."
        )
    molecule = Chem.MolFromMolFile(str(source), removeHs=False, sanitize=False)
    if molecule is None:
        raise RuntimeError(f"RDKit could not parse {source}; provide --obabel/OBABEL_BIN")
    writer = Chem.SDWriter(str(destination))
    writer.write(molecule)
    writer.close()
    return "rdkit"


def make_config(
    args: argparse.Namespace, output_dir: Path, receptor: Path, liged_dir: Path
) -> configparser.ConfigParser:
    root = Path(__file__).resolve().parent
    config = configparser.ConfigParser()
    config.optionxform = str
    config["lib"] = {
        "Cores": str((root / "frag_lib" / "Cores.sdf").resolve()),
        "Frags": str((root / "frag_lib" / "Frags.sdf").resolve()),
    }
    config["model"] = {
        "GPPM": str((root / "weights" / "GPPM.pth").resolve()),
        "TAPM": str((root / "weights" / "TAPM.pth").resolve()),
    }
    sample = {
        "output_dir": str(output_dir.resolve()),
        "receptor": str(receptor.resolve()),
        "ligED_dir": str(liged_dir.resolve()),
        "reference_core": str(args.initial_core.resolve()) if args.initial_core else "",
        "x": "",
        "y": "",
        "z": "",
        "key_res": "",
        "iteration": str(args.iteration),
        "retain_mols_num": str(args.retain_mols_num),
        "output_mols_num": str(args.output_mols_num),
        "bucket_size": str(args.bucket_size),
        "sim_threshold": str(args.sim_threshold),
        "seed": str(args.seed),
        "num_cpu": str(args.num_cpu),
        "batch_size": str(args.batch_size),
        "binding_workers": str(args.binding_workers),
        "device_type": args.device,
        # The engine expects this spelling.
        "tolerence": str(args.tolerance),
    }
    if args.mode == "binding":
        solvent = (
            args.solvent
            if args.solvent is not None
            else ("water" if args.target in METAL_CASES else "")
        )
        sample.update(
            {
                "use_binding_energy": "true",
                "binding_cal_dir": str((output_dir / "xtb_tmp").resolve()),
                "xtb_path": str(Path(args.xtb).resolve()),
                "xtb_method": "gfn2",
                "xtb_opt_level": "normal",
                "preopt": "true",
                "solvent": solvent,
            }
        )
    config["sample"] = sample
    return config


FULL_PROTOCOL = {
    "mask": 0.01,
    "step_size": 0.35,
    "tolerance": 0.3,
    "iteration": 3,
    "retain_mols_num": 80,
    "output_mols_num": 2000,
    "bucket_size": 32,
    "sim_threshold": 0.5,
    "seed": 1234,
    "num_cpu": 32,
    "batch_size": 128,
    "binding_workers": 8,
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--project-root", type=Path, default=Path(__file__).resolve().parents[2]
    )
    parser.add_argument("--target", required=True)
    parser.add_argument("--mode", choices=["binding", "nonbinding"], required=True)
    parser.add_argument(
        "--guest-ed",
        type=Path,
        help="Guest ED .npy; default <project>/examples/guest_ed/<target>.npy",
    )
    parser.add_argument(
        "--host-mol",
        type=Path,
        help="Host MOL; default <project>/examples/host_mol/<target>.mol",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        help="Run directory (default <project>/runs/fragment_growth/<label>/<target>)",
    )
    parser.add_argument(
        "--initial-core",
        type=Path,
        help="Optional SDF whose molecules seed the growth instead of the core library.",
    )
    parser.add_argument("--mask", type=float, default=0.01)
    parser.add_argument("--step-size", type=float, default=0.35)
    parser.add_argument("--tolerance", type=float, default=0.3)
    parser.add_argument("--iteration", type=int, default=3)
    parser.add_argument("--retain-mols-num", type=int, default=80)
    parser.add_argument("--output-mols-num", type=int, default=2000)
    parser.add_argument("--bucket-size", type=int, default=32)
    parser.add_argument("--sim-threshold", type=float, default=0.5)
    parser.add_argument("--seed", type=int, default=1234)
    parser.add_argument("--num-cpu", type=int, default=32)
    parser.add_argument("--batch-size", type=int, default=128)
    parser.add_argument("--binding-workers", type=int, default=8)
    parser.add_argument("--device", default="cuda")
    parser.add_argument(
        "--xtb",
        default=os.environ.get("XTB_BIN", "xtb"),
        help="xTB executable; default from XTB_BIN or PATH",
    )
    parser.add_argument(
        "--obabel",
        default=os.environ.get("OBABEL_BIN", "obabel"),
        help="Open Babel executable; default from OBABEL_BIN or PATH",
    )
    parser.add_argument(
        "--allow-rdkit-converter",
        action="store_true",
        help="Use the RDKit MOL->SDF converter when Open Babel is unavailable.",
    )
    parser.add_argument(
        "--solvent",
        default=None,
        help="ALPB solvent for the complex optimization; default: water for known metal cases, otherwise none",
    )
    parser.add_argument(
        "--execute",
        action="store_true",
        help="Run the growth engine after preparing inputs and config",
    )
    args = parser.parse_args()

    project = args.project_root.resolve()
    args.guest_ed = args.guest_ed or project / "examples" / "guest_ed" / f"{args.target}.npy"
    args.host_mol = args.host_mol or project / "examples" / "host_mol" / f"{args.target}.mol"
    if not args.guest_ed.is_file() or not args.host_mol.is_file():
        raise FileNotFoundError(
            f"Missing input: guest_ed={args.guest_ed}, host_mol={args.host_mol}"
        )
    if args.initial_core is not None:
        args.initial_core = args.initial_core.resolve()
        if not args.initial_core.is_file():
            raise FileNotFoundError(f"Initial core file not found: {args.initial_core}")
    label = "with_binding" if args.mode == "binding" else "without_binding"
    args.output_dir = args.output_dir or (
        project / "runs" / "fragment_growth" / label / f"{args.target}_{args.mask:g}_{args.tolerance:g}"
    )
    output_dir = args.output_dir.resolve()
    if args.execute and args.mode == "binding" and resolve_executable(args.xtb) is None:
        raise FileNotFoundError(f"Binding mode requires an executable xTB: {args.xtb}")
    output_dir.mkdir(parents=True, exist_ok=True)

    rho = np.load(args.guest_ed)
    ed_grid = rho_to_liged_grid(rho, args.step_size, args.mask)
    np.save(output_dir / "ligED.npy", ed_grid)
    receptor = output_dir / f"{args.target}.sdf"
    converter = convert_mol_to_sdf(
        args.host_mol,
        receptor,
        args.obabel,
        allow_rdkit_fallback=args.allow_rdkit_converter,
    )
    config = make_config(args, output_dir, receptor, output_dir)
    config_path = output_dir / "config.ini"
    with config_path.open("w", encoding="utf-8") as handle:
        config.write(handle)

    effective_parameters = {
        "mask": args.mask,
        "step_size": args.step_size,
        "effective_growth_grid_spacing": 47 * args.step_size / 48,
        "tolerance": args.tolerance,
        "iteration": args.iteration,
        "retain_mols_num": args.retain_mols_num,
        "output_mols_num": args.output_mols_num,
        "bucket_size": args.bucket_size,
        "sim_threshold": args.sim_threshold,
        "seed": args.seed,
        "num_cpu": args.num_cpu,
        "batch_size": args.batch_size,
        "binding_workers": args.binding_workers,
        "initial_core": str(args.initial_core) if args.initial_core else None,
    }
    if args.initial_core is not None:
        protocol = "custom"
    elif all(effective_parameters[key] == value for key, value in FULL_PROTOCOL.items()):
        protocol = "full"
    else:
        protocol = "custom"
    manifest = {
        "target": args.target,
        "mode": args.mode,
        "protocol": protocol,
        "source_guest_ed": str(args.guest_ed.resolve()),
        "source_host_mol": str(args.host_mol.resolve()),
        "output_dir": str(output_dir),
        "converter": converter,
        "effective_parameters": effective_parameters,
    }
    (output_dir / "run_manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(f"Prepared {args.mode} case at {output_dir}")
    print(f"Config: {config_path}")
    if args.execute:
        generate = Path(__file__).resolve().parent / "Generate.py"
        subprocess.run(
            [sys.executable, str(generate), "--config", str(config_path)],
            check=True,
            cwd=generate.parent,
        )


if __name__ == "__main__":
    main()
