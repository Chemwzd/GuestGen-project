#!/usr/bin/env bash
# Run the bundled lightweight examples end to end.
#
# Usage:
#   bash examples/run_examples.sh <stage>
#
# Stages:
#   data          preprocessing: augmentation + xTB/Multiwfn ED + LMDB
#   train         ED-VAE smoke training on the bundled LMDB subset
#   infer         guest ED inference with the released checkpoint
#   grow          fragment growth without binding screening
#   grow-binding  fragment growth with binding screening (needs xTB)
#   analyze       summarize the growth outputs
#   all           everything above, in order
#
# Python interpreters are resolved as in scripts/_common.sh (EDVAE_PYTHON /
# FRAG_PYTHON, then conda envs guestgen / e2m, then python).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${SCRIPT_DIR}/../scripts/_common.sh"

STAGE="${1:-all}"
TARGET="${TARGET:-bezcoa}"

# Use the guest ED generated by the infer stage when available, otherwise fall
# back to the bundled precomputed grids.
grow_guest_ed() {
  local generated="${PROJECT_ROOT}/runs/examples/guest_ed/${TARGET}.npy"
  if [ -f "${generated}" ]; then
    printf '%s' "${generated}"
  else
    printf '%s' "${PROJECT_ROOT}/examples/guest_ed/${TARGET}.npy"
  fi
}

run_data()        { bash "${PROJECT_ROOT}/scripts/01_prepare_training_data.sh" all; }
run_train()       { bash "${PROJECT_ROOT}/scripts/02_train_edvae.sh" --smoke; }
run_infer()       { INFERENCE_SEED="${INFERENCE_SEED:-42}" bash "${PROJECT_ROOT}/scripts/04_infer_guest_ed.sh" "${TARGET}"; }
run_grow() {
  bash "${PROJECT_ROOT}/scripts/05_grow_without_binding.sh" "${TARGET}" \
    --guest-ed "$(grow_guest_ed)" --execute
  "$(resolve_python FRAG_PYTHON e2m)" "${PROJECT_ROOT}/tools/check_growth_output.py" \
    "${PROJECT_ROOT}/runs/examples/fragment_growth/without_binding/${TARGET}" --mode nonbinding
}
run_grow_binding() {
  bash "${PROJECT_ROOT}/scripts/06_grow_with_binding.sh" "${TARGET}" \
    --guest-ed "$(grow_guest_ed)" --execute
  "$(resolve_python FRAG_PYTHON e2m)" "${PROJECT_ROOT}/tools/check_growth_output.py" \
    "${PROJECT_ROOT}/runs/examples/fragment_growth/with_binding/${TARGET}" --mode binding
}
run_analyze() {
  bash "${PROJECT_ROOT}/scripts/07_analyze_growth.sh" \
    "${PROJECT_ROOT}/runs/examples/fragment_growth/without_binding/${TARGET}"
  if [ -f "${PROJECT_ROOT}/runs/examples/fragment_growth/with_binding/${TARGET}/output.sdf" ]; then
    bash "${PROJECT_ROOT}/scripts/07_analyze_growth.sh" \
      "${PROJECT_ROOT}/runs/examples/fragment_growth/with_binding/${TARGET}"
  fi
}

case "${STAGE}" in
  data)         run_data ;;
  train)        run_train ;;
  infer)        run_infer ;;
  grow)         run_grow ;;
  grow-binding) run_grow_binding ;;
  analyze)      run_analyze ;;
  all)          run_data; run_train; run_infer; run_grow; run_grow_binding; run_analyze ;;
  *) echo "usage: $0 {data|train|infer|grow|grow-binding|analyze|all}" >&2; exit 2 ;;
esac
